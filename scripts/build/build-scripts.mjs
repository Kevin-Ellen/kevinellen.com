// scripts/build/build-scripts.mjs


import fs from "node:fs/promises";
import path from "node:path";
import { minify } from "terser";

const sourceDir = "src/app/assets/scripts/authored";
const outputDir = "src/app/assets/scripts/generated";

const buildScript = async (filename) => {
  const name = filename.replace(/\.script\.js$/, "");
  const inputPath = path.join(sourceDir, filename);
  const outputPath = path.join(outputDir, `${name}.script.ts`);

  const source = await fs.readFile(inputPath, "utf8");

  const result = await minify(source, {
    compress: true,
    mangle: true,
    format: {
      comments: false,
    },
  });

  if (typeof result.code !== "string") {
    throw new Error(`Terser produced no output for ${filename}`);
  }

  const exportName = `${name.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase()}_SCRIPT`;

  const output = [
    "// Generated by scripts/build/build-scripts.mjs",
    "// Do not edit manually.",
    "",
    `export const ${exportName} = ${JSON.stringify(result.code)};`,
    "",
  ].join("\n");

  await fs.writeFile(outputPath, output, "utf8");
};

const buildScripts = async () => {
  await fs.mkdir(outputDir, { recursive: true });

  const entries = await fs.readdir(sourceDir, {
    withFileTypes: true,
  });

  const filenames = entries
    .filter(
      (entry) =>
        entry.isFile() && entry.name.endsWith(".script.js"),
    )
    .map((entry) => entry.name)
    .sort();

  await Promise.all(filenames.map(buildScript));

  console.log(`Built ${filenames.length} browser script(s).`);
};

await buildScripts();
